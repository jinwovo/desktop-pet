<# Rebuild the original Nimbus/Ember characters from their transparent 3x3 master atlases. #>
param(
    [ValidateSet('All','Nimbus','Ember')][string]$Character = 'All',
    [string]$OutputRoot = '',
    [string]$PreviewPath = ''
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Get-DesktopPetCharacterBehavior.ps1')
Add-Type -AssemblyName System.Drawing
$repoRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot)).TrimEnd('\')
function Resolve-PublicPath([string]$Path) {
    $full = [IO.Path]::GetFullPath($Path)
    if (-not $full.StartsWith($repoRoot + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Generated public assets must stay inside the workspace.' }
    $ancestor = $full
    while ($ancestor -and $ancestor.Length -ge $repoRoot.Length) {
        if ((Test-Path -LiteralPath $ancestor) -and ((Get-Item -LiteralPath $ancestor -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Generated assets cannot traverse links.' }
        $ancestor = [IO.Path]::GetDirectoryName($ancestor)
    }
    return $full
}
$output = Resolve-PublicPath $(if ($OutputRoot) { $OutputRoot } else { Join-Path $repoRoot 'Assets\Characters' })
$preview = Resolve-PublicPath $(if ($PreviewPath) { $PreviewPath } else { Join-Path $repoRoot '.local\public-characters-preview.png' })
$imagesRoot = Join-Path $repoRoot 'images'
if (($output + '\').StartsWith($imagesRoot + '\', [StringComparison]::OrdinalIgnoreCase) -or $preview.StartsWith($imagesRoot + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Generated assets cannot overwrite original images.' }
if ($preview.StartsWith($output + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Preview must stay outside character folders.' }
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition ([IO.File]::ReadAllText((Join-Path $PSScriptRoot 'CharacterBuilder.cs')))
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition ([IO.File]::ReadAllText((Join-Path $PSScriptRoot 'GroundedWalkBuilder.cs')))
$profiles = @(
    @{ Name='Nimbus'; File='public-nimbus-master-v1.png'; Distance=28.0; Speed=52; EyeLeft=49.0; EyeRight=79.0; EyeY=56.0 },
    @{ Name='Ember'; File='public-ember-master-v1.png'; Distance=30.0; Speed=56; EyeLeft=52.0; EyeRight=78.0; EyeY=64.0 }
) | Where-Object { $Character -eq 'All' -or $_.Name -eq $Character }
function Get-PublicRowEdges($Sheet) {
    # Generated atlases preserve three isolated rows, but their transparent gutters need not
    # land at exact thirds. Split at the real gutters instead of clipping a full-body foot.
    $bands=New-Object 'System.Collections.Generic.List[object]';$active=$false;$start=0
    for($y=0;$y-lt$Sheet.Height;$y++){
        $opaque=$false
        for($x=0;$x-lt$Sheet.Width;$x+=3){if($Sheet.GetPixel($x,$y).A-ge25){$opaque=$true;break}}
        if($opaque-and-not$active){$start=$y;$active=$true}
        if(-not$opaque-and$active){$bands.Add(@{Top=$start;Bottom=$y});$active=$false}
    }
    if($active){$bands.Add(@{Top=$start;Bottom=$Sheet.Height})}
    if($bands.Count-ne3){throw 'Public master must contain three separate horizontal rows.'}
    return @(0,[int][Math]::Floor(($bands[0].Bottom+$bands[1].Top)/2.0),[int][Math]::Floor(($bands[1].Bottom+$bands[2].Top)/2.0),$Sheet.Height)
}
function Read-PublicCell($Sheet, [int]$Row, [int]$Column, [int]$Height, [bool]$WholeCharacter, [int[]]$RowEdges) {
    $left=[int][Math]::Floor($Sheet.Width*$Column/3.0); $right=[int][Math]::Floor($Sheet.Width*($Column+1)/3.0)
    $top=$RowEdges[$Row]; $bottom=$RowEdges[$Row+1]
    $cell=[CharacterBuilder]::Crop($Sheet,$left,$top,$right-$left,$bottom-$top)
    $trimmed=$null
    try {
        $bounds=[CharacterBuilder]::OpaqueBounds($cell,25)
        if ($bounds.Width -lt 1 -or $bounds.Height -lt 1 -or $bounds.Left -le 0 -or $bounds.Right -ge $cell.Width -or $bounds.Top -le 0 -or $bounds.Bottom -ge $cell.Height) { throw 'Master cells must be complete isolated transparent cutouts.' }
        $trimmed=[CharacterBuilder]::Trim($cell,25)
        if ($WholeCharacter) {
            $anchor=0
            return [CharacterBuilder]::Normalize($trimmed,128,128,100,6,[ref]$anchor)
        }
        return [GroundedWalkBuilder]::ResizePart($trimmed,$Height)
    } finally { if ($trimmed) {$trimmed.Dispose()}; $cell.Dispose() }
}
function Save-PublicFrame([string]$Folder,[string]$Name,$Bitmap) {
    try { [CharacterBuilder]::Save($Bitmap,(Resolve-PublicPath (Join-Path $Folder $Name))) } finally { $Bitmap.Dispose() }
}
foreach ($profile in $profiles) {
    $folder=Resolve-PublicPath (Join-Path $output $profile.Name)
    $marker=Join-Path $folder '.desktop-pet-public-generated'
    if ([IO.Directory]::Exists($folder) -and -not [IO.File]::Exists($marker) -and @(Get-ChildItem -LiteralPath $folder -Force).Count -gt 0) { throw 'Output character folder must be empty or previously generated by this script.' }
    if ([IO.File]::Exists($marker) -and [IO.File]::ReadAllText($marker) -ne 'DesktopPet.PublicCharacter.v1') { throw 'Unrecognized character output marker.' }
    $sheet=[CharacterBuilder]::LoadArgb((Resolve-PublicPath (Join-Path $imagesRoot $profile.File)))
    $front=@(); $parts=@()
    try {
        if ($sheet.GetPixel(0,0).A -ne 0) { throw 'Public master requires transparent alpha.' }
        $rowEdges=Get-PublicRowEdges $sheet
        foreach ($column in 0..2) { $front+=Read-PublicCell $sheet 0 $column 100 $true $rowEdges }
        foreach ($row in 1..2) {
            $parts+=Read-PublicCell $sheet $row 0 90 $false $rowEdges
            $parts+=Read-PublicCell $sheet $row 1 12 $false $rowEdges
            $parts+=Read-PublicCell $sheet $row 2 11 $false $rowEdges
        }
        [void][IO.Directory]::CreateDirectory($folder)
        [IO.File]::WriteAllText($marker,'DesktopPet.PublicCharacter.v1',(New-Object Text.UTF8Encoding $false))
        Save-PublicFrame $folder 'idle.png' ([CharacterBuilder]::PoseGrounded($front[0],122,0,0))
        Save-PublicFrame $folder 'blink.png' ([CharacterBuilder]::PoseGrounded($front[1],122,0,0))
        Save-PublicFrame $folder 'sit.png' ([CharacterBuilder]::PoseGrounded($front[0],122,0,0))
        Save-PublicFrame $folder 'drag.png' ([CharacterBuilder]::Pose($front[0],122,1,1,-3,0,0))
        Save-PublicFrame $folder 'fall.png' ([CharacterBuilder]::Pose($front[0],122,1,1,4,0,0))
        $right=[GroundedWalkBuilder]::Render($parts[3],$parts[4],$parts[5],0,$profile.Distance,4,1)
        Save-PublicFrame $folder 'look_right.png' $right
        $left=[GroundedWalkBuilder]::Render($parts[3],$parts[4],$parts[5],0,$profile.Distance,4,1)
        $left.RotateFlip([Drawing.RotateFlipType]::RotateNoneFlipX)
        Save-PublicFrame $folder 'look_left.png' $left
        foreach ($view in 0..1) {
            $prefix=if ($view -eq 0) {'rig_side'} else {'rig_turn'}; $offset=$view*3
            Save-PublicFrame $folder ($prefix+'_body.png') ([GroundedWalkBuilder]::ExportPart($parts[$offset],$true,$false))
            Save-PublicFrame $folder ($prefix+'_near.png') ([GroundedWalkBuilder]::ExportPart($parts[$offset+1],$false,$false))
            Save-PublicFrame $folder ($prefix+'_far.png') ([GroundedWalkBuilder]::ExportPart($parts[$offset+2],$false,$true))
        }
        $walk=@(); $turn=@(); $settleSide=@(); $settleTurn=@(); $audit=@()
        foreach ($i in 0..31) {
            $phase=$i/32.0; $pose=[GroundedWalkBuilder]::Sample($phase,$profile.Distance,4)
            $walkName='walk_{0}.png' -f ($i+1); $turnName='walk_turn_{0}.png' -f ($i+1)
            $walk+=$walkName; $turn+=$turnName
            Save-PublicFrame $folder $walkName ([GroundedWalkBuilder]::Render($parts[0],$parts[1],$parts[2],$phase,$profile.Distance,4,0))
            Save-PublicFrame $folder $turnName ([GroundedWalkBuilder]::Render($parts[3],$parts[4],$parts[5],$phase,$profile.Distance,4,0))
            $audit+=@{ phase=$phase; near=@{x=$pose.Near.X;lift=$pose.Near.Lift;planted=$pose.Near.IsPlanted}; far=@{x=$pose.Far.X;lift=$pose.Far.Lift;planted=$pose.Far.IsPlanted}; bodyBob=$pose.BodyBob }
        }
        foreach ($level in 1..2) { foreach ($i in 0..31) {
            $sideName='settle_side_{0}_{1}.png' -f $level,($i+1); $turnName='settle_turn_{0}_{1}.png' -f $level,($i+1)
            $settleSide+=$sideName; $settleTurn+=$turnName
            Save-PublicFrame $folder $sideName ([GroundedWalkBuilder]::Render($parts[0],$parts[1],$parts[2],$i/32.0,$profile.Distance,4,$level/2.0))
            Save-PublicFrame $folder $turnName ([GroundedWalkBuilder]::Render($parts[3],$parts[4],$parts[5],$i/32.0,$profile.Distance,4,$level/2.0))
        }}
        foreach ($i in 0..1) {
            $frame=[CharacterBuilder]::PoseGrounded($front[0],122,0,0)
            [CharacterBuilder]::DrawTearsAt($frame,$profile.EyeLeft,$profile.EyeY,$profile.EyeRight,$profile.EyeY,$(if($i -eq 0){0.15}else{0.85}))
            Save-PublicFrame $folder ('cry_{0}.png' -f ($i+1)) $frame
            $frame=[CharacterBuilder]::PoseGrounded($front[0],122,0,0)
            [CharacterBuilder]::TintRed($frame,0.04+$i*0.01)
            [CharacterBuilder]::DrawAngerMark($frame,122,100,$i*0.3)
            Save-PublicFrame $folder ('angry_{0}.png' -f ($i+1)) $frame
            Save-PublicFrame $folder ('sleep_{0}.png' -f ($i+1)) ([CharacterBuilder]::PoseGrounded($front[2],122,0,0))
        }
        $metadata=[ordered]@{
            name=$profile.Name; scale=1; assetKind='original-public'; frontFacingRest=$true
            frameSizePx=@{width=128;height=128};anchor=@{x=64;y=122};walkSpeedPxPerSec=$profile.Speed;frameIntervalMs=100
            frames=[ordered]@{idle=@('idle.png','blink.png','idle.png','blink.png');walk=$walk;walkTurn=$turn;walkFront=@('idle.png')*32;walkSettleSide=$settleSide;walkSettleTurn=$settleTurn;sit=@('sit.png');lookLeft=@('look_left.png');lookRight=@('look_right.png');drag=@('drag.png');fall=@('fall.png');cry=@('cry_1.png','cry_2.png');angry=@('angry_1.png','angry_2.png');sleep=@('sleep_1.png','sleep_2.png')}
            frameDurationsMs=@{idle=@(4200,120,3300,110)}
            eyePositionsPx=@{left=@{x=$profile.EyeLeft;y=$profile.EyeY};right=@{x=$profile.EyeRight;y=$profile.EyeY}}
            walkCycleDistancePx=$profile.Distance
            walkRig=@{version=1;footLiftPx=3;side=@{body='rig_side_body.png';nearFoot='rig_side_near.png';farFoot='rig_side_far.png'};turn=@{body='rig_turn_body.png';nearFoot='rig_turn_near.png';farFoot='rig_turn_far.png'}}
            groundedWalk=@{version=1;frameCount=32;stanceFraction=0.6;footLiftPx=4;settleLevels=2;bodyHeightPx=90;hipY=112;contactY=122;contacts=$audit}
        }
        Set-DesktopPetCharacterBehavior -Definition $metadata -Name $profile.Name
        [IO.File]::WriteAllText((Join-Path $folder 'character.json'),($metadata|ConvertTo-Json -Depth 12),(New-Object Text.UTF8Encoding $false))
        Write-Output "Original public character built: $($profile.Name)"
    } finally { foreach ($bitmap in $front+$parts) {$bitmap.Dispose()}; $sheet.Dispose() }
}
$names=@('Companion','Nimbus','Ember')|Where-Object{[IO.File]::Exists((Join-Path (Join-Path $output $_) 'character.json'))}
$samples=@('idle.png','walk_9.png','walk_turn_9.png','blink.png','sleep_1.png','cry_1.png')
$labels=@('Idle','Side walk','Quarter','Blink','Sleep','Tears')
[void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($preview))
$sheet=New-Object Drawing.Bitmap (160*$samples.Count),(190*$names.Count)
$graphics=[Drawing.Graphics]::FromImage($sheet);$font=New-Object Drawing.Font 'Segoe UI',10;$brush=New-Object Drawing.SolidBrush ([Drawing.Color]::FromArgb(47,65,58))
try {
    $graphics.Clear([Drawing.Color]::FromArgb(244,247,242))
    for($row=0;$row-lt$names.Count;$row++){for($column=0;$column-lt$samples.Count;$column++){
        $graphics.DrawString(($names[$row]+' / '+$labels[$column]),$font,$brush,[single]($column*160+8),[single]($row*190+10))
        $frame=[CharacterBuilder]::LoadArgb((Join-Path (Join-Path $output $names[$row]) $samples[$column]))
        try{$graphics.DrawImageUnscaled($frame,$column*160+16,$row*190+42)}finally{$frame.Dispose()}
    }}
    [CharacterBuilder]::Save($sheet,$preview)
}finally{$brush.Dispose();$font.Dispose();$graphics.Dispose();$sheet.Dispose()}
Write-Output "Public character preview: $preview"
