<#
.SYNOPSIS
    images\ 폴더의 그림들을 훑어서 DesktopPet 캐릭터를 자동으로 만들어낸다.

.DESCRIPTION
    원하는 캐릭터 그림을 images\ 폴더에 넣고 이 스크립트를 돌리기만 하면 된다. 좌표를 적거나
    설정을 건드릴 필요가 없다. 스크립트가 알아서 판단하는 것들:

      * 배경 — 테두리 픽셀을 투표해서 배경색을 찾고(흰색이든 분홍이든), 이미 투명하면 건너뛴다.
      * 캐릭터 개수 — 덩어리(연결 요소) 분석으로 떨어져 있는 캐릭터들을 분리하고,
        손을 잡고 붙어 있어서 한 덩어리가 된 경우는 '이음새'(세로로 그림이 가장 적은 열)를
        찾아 다시 쪼갠다.
      * 포즈 — 원본은 보통 정면 한 장뿐이므로 걷기/앉기/울기/화내기 프레임을 변형으로 합성한다.

    캐릭터 이름은 파일 이름에서 따온다. 한 그림에 여러 캐릭터가 있으면 왼쪽부터 번호가 붙는다
    (예: trio.png -> trio1, trio2, trio3).

    이름을 직접 정하고 싶으면 images\overrides.json 을 만들어 두면 된다:
        {
          "trio.png":  { "names": ["Hachiware", "Chiikawa", "Usagi"], "walkSpeed": 65 },
          "images.jpg": { "names": ["Chiikawa"], "walkSpeed": 55 }
        }

.EXAMPLE
    .\scripts\build-characters.ps1
    .\scripts\build-characters.ps1 -Clean      # 기존 캐릭터 폴더를 지우고 새로 생성
#>
param(
    [ValidateRange(64, 1024)]
    [int]$CanvasSize = 128,
    [int]$TargetHeight = 100,
    [int]$BottomMargin = 6,
    [int]$BackgroundTolerance = 18,
    # Retained for older callers; the preservation-based renderer no longer cuts foot bands.
    [double]$FootBandRatio = 0.17,
    [switch]$Clean,
    [string]$OutputDirectory,
    [string]$PreviewDirectory
)

$ErrorActionPreference = "Stop"

Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName PresentationCore
Add-Type -AssemblyName WindowsBase

$repoRoot = Split-Path -Parent $PSScriptRoot
$helperSource = Get-Content (Join-Path $PSScriptRoot "CharacterBuilder.cs") -Raw
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition $helperSource

$imagesDir = Join-Path $repoRoot "images"
$defaultCharactersRoot = [System.IO.Path]::GetFullPath((Join-Path $repoRoot "Assets\Characters"))
$charactersRoot = if ($OutputDirectory) { [System.IO.Path]::GetFullPath($OutputDirectory).TrimEnd('\') } else { $defaultCharactersRoot }
$outputMarker = Join-Path $charactersRoot '.desktop-pet-generated'
# An explicit output folder must be new/empty or previously generated. Never let -Clean turn
# a repository, source-image directory, drive root or an unrelated folder into a deletion target.
$outputPrefix = $charactersRoot.TrimEnd('\') + '\'
if ($repoRoot.StartsWith($outputPrefix, [StringComparison]::OrdinalIgnoreCase) -or
    $repoRoot.Equals($charactersRoot, [StringComparison]::OrdinalIgnoreCase) -or
    $charactersRoot.Equals($imagesDir, [StringComparison]::OrdinalIgnoreCase) -or
    $charactersRoot.StartsWith($imagesDir + '\', [StringComparison]::OrdinalIgnoreCase)) {
    throw "Refusing to use a source or repository root as character output: $charactersRoot"
}
$outputAncestor = $charactersRoot
while ($outputAncestor) {
    if (Test-Path -LiteralPath $outputAncestor) {
        $outputItem = Get-Item -LiteralPath $outputAncestor -Force
        if (-not $outputItem.PSIsContainer -or ($outputItem.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
            throw "Character output cannot traverse a file or reparse point: $outputAncestor"
        }
    }
    $outputAncestor = [System.IO.Path]::GetDirectoryName($outputAncestor)
}
if ((Test-Path -LiteralPath $charactersRoot) -and $charactersRoot -ne $defaultCharactersRoot -and
    -not (Test-Path -LiteralPath $outputMarker) -and @(Get-ChildItem -LiteralPath $charactersRoot -Force).Count -gt 0) {
    throw "OutputDirectory must be empty or previously generated by this script: $charactersRoot"
}
if ((Test-Path -LiteralPath $outputMarker) -and
    [System.IO.File]::ReadAllText($outputMarker).Trim() -ne 'DesktopPet.CharacterBuilder.v2') {
    throw "Unrecognized character output marker: $outputMarker"
}

if (-not (Test-Path $imagesDir)) {
    throw "images 폴더가 없습니다: $imagesDir"
}

$overrides = @{}
$overridePath = Join-Path $imagesDir "overrides.json"
if (Test-Path $overridePath) {
    $raw = Get-Content $overridePath -Raw | ConvertFrom-Json
    foreach ($prop in $raw.PSObject.Properties) { $overrides[$prop.Name] = $prop.Value }
    Write-Host "overrides.json 적용 ($($overrides.Count)개 항목)" -ForegroundColor DarkGray
}

# Preserve the source artwork's aspect ratio in every state. A still image cannot supply a
# real new limb pose: subtle rigid movement is preferable to slicing or squashing the artwork.
$Poses = @(
    @{ File = "idle.png"; Rotate = 0.0; Grounded = $true }
    @{ File = "idle_2.png"; Rotate = 0.18; Grounded = $true }
    @{ File = "sit.png"; Rotate = 0.0; Grounded = $true }
    @{ File = "look_left.png"; Rotate = -0.8; Grounded = $true }
    @{ File = "look_right.png"; Rotate = 0.8; Grounded = $true }
    @{ File = "drag.png"; Rotate = -4.0; Grounded = $false }
    @{ File = "fall.png"; Rotate = 6.0; Grounded = $false }
)

# Eight evenly spaced samples make the sway continuous; the feet remain at the same baseline.
$WalkFrames = @(0..7 | ForEach-Object {
    $phase = 2.0 * [Math]::PI * $_ / 8.0
    @{ File = ("walk_{0}.png" -f ($_ + 1)); Rotate = 0.85 * [Math]::Sin($phase); Dx = 0.2 * [Math]::Sin($phase) }
})
$CryPoses = @(
    @{ File = "cry_1.png"; Drop = 0.15 }
    @{ File = "cry_2.png"; Drop = 0.85 }
)
$AngryPoses = @(
    @{ File = "angry_1.png"; Rotate = -0.5; Tint = 0.06; Pulse = 0.0 }
    @{ File = "angry_2.png"; Rotate = 0.5; Tint = 0.09; Pulse = 0.5 }
)
$SleepPoses = @(
    @{ File = "sleep_1.png"; Rotate = -1.0; Drift = 0.0 }
    @{ File = "sleep_2.png"; Rotate = -1.15; Drift = 0.6 }
)

<#
    Loads any image into a GDI+ bitmap. System.Drawing can't read .webp, so route everything it
    rejects through the WPF imaging stack, which can -- preserving alpha.
#>
function Import-SourceImage {
    param([string]$Path)
    try { return [CharacterBuilder]::LoadArgb($Path) }
    catch {
        $tmp = Join-Path $env:TEMP ("DesktopPet-decode-" + [Guid]::NewGuid().ToString("N") + ".png")
        try {
            try {
                $decoder = [System.Windows.Media.Imaging.BitmapDecoder]::Create((New-Object System.Uri $Path), 'PreservePixelFormat', 'OnLoad')
                $enc = New-Object System.Windows.Media.Imaging.PngBitmapEncoder
                $enc.Frames.Add([System.Windows.Media.Imaging.BitmapFrame]::Create($decoder.Frames[0]))
                $fs = [System.IO.File]::Open($tmp, 'Create')
                try { $enc.Save($fs) } finally { $fs.Dispose() }
            }
            catch {
                # Some Windows installations do not have a WIC WebP codec. Pillow is an optional
                # fallback; ordinary PNG/JPEG inputs continue to need only Windows/.NET.
                $python = Get-Command python -ErrorAction SilentlyContinue
                if (-not $python) { throw "Cannot decode image; install a WebP codec or Python Pillow: $Path" }
                & $python.Source -c "from PIL import Image; import sys; Image.open(sys.argv[1]).convert('RGBA').save(sys.argv[2],'PNG')" $Path $tmp
                if ($LASTEXITCODE -ne 0) { throw "Image conversion failed: $Path" }
            }
            return [CharacterBuilder]::LoadArgb($tmp)
        }
        finally { if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Force } }
    }
}

<# Turns one extracted sprite region into a full character folder. #>
function New-CharacterFromRegion {
    param($Source, [int]$LeftBoundary, [int]$RightBoundary, [string]$Name, [int]$WalkSpeed, $Eyes)

    $outDir = Join-Path $charactersRoot $Name
    if ((Test-Path -LiteralPath $outDir) -and
        ((Get-Item -LiteralPath $outDir -Force).Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
        throw "Character folder cannot be a reparse point: $outDir"
    }
    New-Item -ItemType Directory -Force -Path $outDir | Out-Null

    $region = [CharacterBuilder]::ExtractBetweenSeams($Source, $LeftBoundary, $RightBoundary, 48)
    $trimmed = [CharacterBuilder]::Trim($region, 25)
    $region.Dispose()

    $anchorY = 0
    $base = [CharacterBuilder]::Normalize($trimmed, $CanvasSize, $CanvasSize, $TargetHeight, $BottomMargin, [ref]$anchorY)
    $trimmed.Dispose()

    foreach ($pose in $Poses) {
        $frame = if ($pose.Grounded) { [CharacterBuilder]::PoseGrounded($base, $anchorY, $pose.Rotate, 0) } else { [CharacterBuilder]::Pose($base, $anchorY, 1, 1, $pose.Rotate, 0, 0) }
        [CharacterBuilder]::Save($frame, (Join-Path $outDir $pose.File))
        $frame.Dispose()
    }

    foreach ($wf in $WalkFrames) {
        $frame = [CharacterBuilder]::PoseGrounded($base, $anchorY, $wf.Rotate, $wf.Dx)
        [CharacterBuilder]::Save($frame, (Join-Path $outDir $wf.File))
        $frame.Dispose()
    }
    $bounds = [CharacterBuilder]::OpaqueBounds($base, 100)
    # eyes maps the character name to [leftX,leftY,rightX,rightY], relative to artwork bounds.
    if (-not $Eyes) { $Eyes = @(0.35, 0.42, 0.65, 0.42) }
    if ($Eyes.Count -ne 4) { throw "Eye landmarks must contain four coordinates: $Name" }
    foreach ($coordinate in $Eyes) {
        $number = [double]$coordinate
        if ([double]::IsNaN($number) -or [double]::IsInfinity($number) -or $number -lt 0 -or $number -gt 1) {
            throw "Eye landmark coordinates must be finite values between 0 and 1: $Name"
        }
    }
    $eyeLeftX = $bounds.Left + $bounds.Width * [double]$Eyes[0]
    $eyeLeftY = $bounds.Top + $bounds.Height * [double]$Eyes[1]
    $eyeRightX = $bounds.Left + $bounds.Width * [double]$Eyes[2]
    $eyeRightY = $bounds.Top + $bounds.Height * [double]$Eyes[3]
    foreach ($pose in $CryPoses) {
        $frame = [CharacterBuilder]::PoseGrounded($base, $anchorY, 0, 0)
        [CharacterBuilder]::DrawTearsAt($frame, $eyeLeftX, $eyeLeftY, $eyeRightX, $eyeRightY, $pose.Drop)
        [CharacterBuilder]::Save($frame, (Join-Path $outDir $pose.File))
        $frame.Dispose()
    }
    foreach ($pose in $AngryPoses) {
        $frame = [CharacterBuilder]::PoseGrounded($base, $anchorY, $pose.Rotate, 0)
        [CharacterBuilder]::TintRed($frame, $pose.Tint)
        [CharacterBuilder]::DrawAngerMark($frame, $anchorY, $TargetHeight, $pose.Pulse)
        [CharacterBuilder]::Save($frame, (Join-Path $outDir $pose.File))
        $frame.Dispose()
    }

    foreach ($pose in $SleepPoses) {
        $frame = [CharacterBuilder]::PoseGrounded($base, $anchorY, $pose.Rotate, 0)
        [CharacterBuilder]::DrawSleepMark($frame, $anchorY, $TargetHeight, $pose.Drift)
        [CharacterBuilder]::Save($frame, (Join-Path $outDir $pose.File))
        $frame.Dispose()
    }
    $base.Dispose()

    $json = [ordered]@{
        name = $Name; scale = 1.0
        frameSizePx = @{ width = $CanvasSize; height = $CanvasSize }
        anchor = @{ x = [int]($CanvasSize / 2); y = $anchorY }
        walkSpeedPxPerSec = $WalkSpeed
        frames = [ordered]@{
            idle = @('idle.png', 'idle_2.png')
            walk = @($WalkFrames | ForEach-Object { $_.File })
            sit = @('sit.png'); lookLeft = @('look_left.png'); lookRight = @('look_right.png')
            drag = @('drag.png'); fall = @('fall.png')
            cry = @('cry_1.png', 'cry_2.png'); angry = @('angry_1.png', 'angry_2.png')
            sleep = @('sleep_1.png', 'sleep_2.png')
        }
        frameIntervalMs = 100
        eyePositionsPx = @{ left = @{ x = $eyeLeftX; y = $eyeLeftY }; right = @{ x = $eyeRightX; y = $eyeRightY } }
    } | ConvertTo-Json -Depth 6
    Set-Content -Path (Join-Path $outDir "character.json") -Value $json -Encoding UTF8
}

function ConvertTo-SafeName {
    param([string]$Raw)
    # .NET's \w already covers Unicode letters, so Korean/Japanese names survive this.
    $clean = ($Raw -replace '[^\w\-]', '')
    if ([string]::IsNullOrWhiteSpace($clean)) { return "Character" }
    return $clean
}

if ($Clean -and (Test-Path $charactersRoot)) {
    Write-Host "기존 캐릭터 폴더 삭제 중..." -ForegroundColor DarkGray
    $cleanRoot = [System.IO.Path]::GetFullPath($charactersRoot).TrimEnd('\') + '\'
    foreach ($child in Get-ChildItem -LiteralPath $charactersRoot -Directory) {
        $cleanTarget = [System.IO.Path]::GetFullPath($child.FullName)
        if (-not $cleanTarget.StartsWith($cleanRoot, [StringComparison]::OrdinalIgnoreCase) -or
            ($child.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) { throw "Unsafe cleanup path: $cleanTarget" }
        if (Test-Path -LiteralPath (Join-Path $cleanTarget 'character.json')) {
            $pending = New-Object 'System.Collections.Generic.Stack[string]'
            $pending.Push($cleanTarget)
            while ($pending.Count -gt 0) {
                foreach ($entry in Get-ChildItem -LiteralPath ($pending.Pop()) -Force) {
                    if (($entry.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -or
                        -not [System.IO.Path]::GetFullPath($entry.FullName).StartsWith($cleanRoot, [StringComparison]::OrdinalIgnoreCase)) {
                        throw "Refusing cleanup through a reparse point or outside the output root: $($entry.FullName)"
                    }
                    if ($entry.PSIsContainer) { $pending.Push($entry.FullName) }
                }
            }
            Remove-Item -LiteralPath $cleanTarget -Recurse -Force
        }
    }
}

$imageFiles = Get-ChildItem $imagesDir -File |
    Where-Object { $_.Extension -match '^\.(png|jpg|jpeg|webp|bmp|gif)$' } |
    Sort-Object Name

if ($imageFiles.Count -eq 0) {
    throw "images 폴더에 이미지가 없습니다: $imagesDir"
}

$made = 0
foreach ($file in $imageFiles) {
    Write-Host ""
    Write-Host "== $($file.Name)" -ForegroundColor Cyan

    $ov = $overrides[$file.Name]
    if ($ov -and $ov.skip) {
        Write-Host "   overrides.json에서 skip 지정됨 — 건너뜀" -ForegroundColor DarkGray
        continue
    }
    $walkSpeed = if ($ov -and $ov.walkSpeed) { [int]$ov.walkSpeed } else { 60 }

    $img = Import-SourceImage -Path $file.FullName
    if ($PreviewDirectory) {
        New-Item -ItemType Directory -Path $PreviewDirectory -Force | Out-Null
        [CharacterBuilder]::Save($img, (Join-Path $PreviewDirectory ($file.BaseName + '-source.png')))
    }
    $usedTol = $BackgroundTolerance
    $usedRadius = 1

    $bg = [CharacterBuilder]::DetectBackgroundColor($img)
    if ($bg -lt 0) {
        Write-Host "   배경: 이미 투명"
    }
    else {
        $r = ($bg -shr 16) -band 0xFF; $g = ($bg -shr 8) -band 0xFF; $b = $bg -band 0xFF
        Write-Host ("   배경: RGB({0},{1},{2})" -f $r, $g, $b)

        # A white character on a white background is the hard case: line art often leaves the
        # outline *open* (limbs drawn as separate strokes), so the fill pours through the gap and
        # eats the body, leaving a hollow shell. Rather than hand-tuning per image, try
        # progressively tighter tolerances with wider gap-sealing, and keep the first result whose
        # largest shape is still solid (see LargestBlobFillRatio).
        $attempts = @(
            @{ Tol = $BackgroundTolerance; R = 1 }
            @{ Tol = 12; R = 2 }
            @{ Tol = 10; R = 3 }
            @{ Tol = 8;  R = 5 }
            @{ Tol = 6;  R = 8 }
            @{ Tol = 5;  R = 12 }
        )

        $cleaned = $null
        foreach ($try in $attempts) {
            $candidate = [CharacterBuilder]::LoadArgbFrom($img)
            [CharacterBuilder]::RemoveBackground($candidate, $bg, $try.Tol, $try.R)
            $fill = [CharacterBuilder]::LargestBlobFillRatio($candidate)

            if ($fill -ge 0.35) {
                $cleaned = $candidate
                $usedTol = $try.Tol
                $usedRadius = $try.R
                Write-Host ("   제거 tolerance={0} gap={1} (채움률 {2:P0})" -f $try.Tol, $try.R, $fill)
                break
            }

            Write-Host ("   tolerance={0} gap={1} -> 채움률 {2:P0}, 재시도" -f $try.Tol, $try.R, $fill) -ForegroundColor DarkYellow
            $candidate.Dispose()
        }

        if (-not $cleaned) {
            Write-Host "   배경을 안전하게 제거하지 못해 건너뜁니다." -ForegroundColor Red
            $img.Dispose()
            continue
        }

        $img.Dispose()
        $img = $cleaned
    }

    # Separate blobs first; then split any blob wide enough to be several joined characters.
    # Low threshold so detached limb strokes are seen at all; FindBlobs merges them into bodies.
    $flat = [CharacterBuilder]::FindBlobs($img, 0.0015)
    $blobs = @()
    for ($i = 0; $i -lt $flat.Length; $i += 4) {
        $blobs += ,@{ X = $flat[$i]; Y = $flat[$i+1]; W = $flat[$i+2]; H = $flat[$i+3] }
    }

    $regions = @()
    foreach ($blob in $blobs) {
        $cuts = @([CharacterBuilder]::FindSplitColumns($img, $blob.X, $blob.Y, $blob.W, $blob.H))
        if ($cuts.Count -eq 0) {
            $regions += ,$blob
            continue
        }

        $edges = @($blob.X) + $cuts + @($blob.X + $blob.W)
        for ($i = 0; $i -lt $edges.Count - 1; $i++) {
            $regions += ,@{ X = $edges[$i]; Y = $blob.Y; W = ($edges[$i+1] - $edges[$i]); H = $blob.H }
        }
    }

    # Left-to-right, so override name lists line up with what a person sees.
    $regions = @($regions | Sort-Object { $_.X })
    Write-Host "   캐릭터 $($regions.Count)개 감지"

    # Only now shave the halo the gap-sealing barrier left around the character. Doing it earlier
    # would re-sever the limb strokes the barrier had bridged, and blob detection would see one
    # character as a handful of pieces again. The regions are already fixed, so losing those
    # bridges here is harmless -- and the sprite's bounds become the character, not the halo.
    if ($usedRadius -gt 1) {
        [CharacterBuilder]::ShrinkFringe($img, $bg, [Math]::Max($usedTol, 20), 1, $usedRadius)
    }
    if ($bg -ge 0) {
        [CharacterBuilder]::FeatherEdges($img, $bg, $usedTol)
    }

    $baseName = ConvertTo-SafeName ([System.IO.Path]::GetFileNameWithoutExtension($file.Name))
    for ($i = 0; $i -lt $regions.Count; $i++) {
        $region = $regions[$i]

        $name = $null
        if ($ov -and $ov.names -and $i -lt $ov.names.Count) { $name = ConvertTo-SafeName $ov.names[$i] }
        if (-not $name) { $name = if ($regions.Count -eq 1) { $baseName } else { "$baseName$($i + 1)" } }

        $leftBoundary = if ($i -eq 0) { -1 } else { [int](($regions[$i-1].X + $regions[$i-1].W + $region.X) / 2) }
        $rightBoundary = if ($i -eq $regions.Count - 1) { -1 } else { [int](($region.X + $region.W + $regions[$i+1].X) / 2) }
        $eyes = if ($ov -and $ov.eyes) { $ov.eyes.PSObject.Properties[$name].Value } else { $null }
        New-CharacterFromRegion -Source $img -LeftBoundary $leftBoundary -RightBoundary $rightBoundary `
            -Name $name -WalkSpeed $walkSpeed -Eyes $eyes
        Write-Host "     -> $name" -ForegroundColor Green
        $made++
    }

    $img.Dispose()
}

Write-Host ""
Write-Host "캐릭터 $($made)개 생성 완료 -> $charactersRoot" -ForegroundColor Green
if ($made -gt 0 -and $charactersRoot -ne $defaultCharactersRoot) {
    [System.IO.File]::WriteAllText($outputMarker, 'DesktopPet.CharacterBuilder.v2')
}

# A regular generator export makes visual reviews reproducible without touching source images.
if ($PreviewDirectory) {
    New-Item -ItemType Directory -Path $PreviewDirectory -Force | Out-Null
    $names = @(Get-ChildItem -LiteralPath $charactersRoot -Directory | Sort-Object Name)
    $states = @('idle', 'walk_2', 'walk_6', 'cry_1', 'cry_2', 'sleep_1')
    $board = New-Object System.Drawing.Bitmap ($states.Count * 264),($names.Count * 292)
    $graphics = [System.Drawing.Graphics]::FromImage($board)
    $font = New-Object System.Drawing.Font 'Segoe UI',14
    try {
        $graphics.Clear([System.Drawing.Color]::FromArgb(228,233,239))
        for ($row = 0; $row -lt $names.Count; $row++) {
            for ($column = 0; $column -lt $states.Count; $column++) {
                $graphics.DrawString(($names[$row].Name + ' / ' + $states[$column]), $font, [System.Drawing.Brushes]::Black, ($column * 264), ($row * 292))
                $sprite = [System.Drawing.Image]::FromFile((Join-Path $names[$row].FullName ($states[$column] + '.png')))
                try { $graphics.InterpolationMode = 'NearestNeighbor'; $graphics.DrawImage($sprite, ($column * 264), ($row * 292 + 30), 256, 256) }
                finally { $sprite.Dispose() }
            }
        }
        $board.Save((Join-Path $PreviewDirectory 'contact-sheet.png'))
    }
    finally { $font.Dispose(); $graphics.Dispose(); $board.Dispose() }
}
