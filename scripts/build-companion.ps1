<#
.SYNOPSIS
    정면 원화와 방향별 걷기 원화에서 배포용 Companion 프레임을 생성한다.
.DESCRIPTION
    왼쪽은 눈을 뜬 원화, 가운데는 깜박임, 오른쪽은 잠든 원화다.
    방향별 원화는 2행 4열이다. 위는 오른쪽 옆모습, 아래는 오른쪽 사선 모습이며 각 행은 네 걸음 단계다.
    원본 비율을 유지하며, 옆모습과 사선을 거쳐 정면으로 시선을 바꿀 수 있게 생성한다.
#>
param([string]$OutputDirectory = '', [string]$PreviewPath = '')
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Get-DesktopPetCharacterBehavior.ps1')
Add-Type -AssemblyName System.Drawing
$repoRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot)).TrimEnd('\')
$rootPrefix = $repoRoot + '\'

function Resolve-CompanionPath([string]$Path) {
    $full = [IO.Path]::GetFullPath($Path)
    if (-not $full.StartsWith($rootPrefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Companion generation paths must stay inside the workspace: $full"
    }
    $ancestor = $full
    while ($ancestor -and $ancestor.Length -ge $repoRoot.Length) {
        if (Test-Path -LiteralPath $ancestor) {
            $item = Get-Item -LiteralPath $ancestor -Force
            if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Companion paths cannot traverse reparse points: $ancestor" }
        }
        $ancestor = [IO.Path]::GetDirectoryName($ancestor)
    }
    return $full
}

$sourcePath = Resolve-CompanionPath (Join-Path $repoRoot 'images\companion-master-v1.png')
$directionalPath = Resolve-CompanionPath (Join-Path $repoRoot 'images\companion-walk-master-v2.png')
$defaultOutput = Join-Path $repoRoot 'Assets\Characters\Companion'
$output = Resolve-CompanionPath $(if ($OutputDirectory) { $OutputDirectory } else { $defaultOutput })
$preview = Resolve-CompanionPath $(if ($PreviewPath) { $PreviewPath } else { Join-Path $repoRoot '.local\companion-preview.png' })
$marker = Resolve-CompanionPath (Join-Path $output '.desktop-pet-companion-generated')
$imagesPrefix = [IO.Path]::GetDirectoryName($sourcePath).TrimEnd('\') + '\'
if (($output.TrimEnd('\') + '\').StartsWith($imagesPrefix, [StringComparison]::OrdinalIgnoreCase) -or
    $preview.StartsWith($imagesPrefix, [StringComparison]::OrdinalIgnoreCase) -or
    $preview.StartsWith($output.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Generated frames and preview cannot overwrite source images or each other.'
}
if ((Test-Path -LiteralPath $output) -and -not (Test-Path -LiteralPath $output -PathType Container)) { throw 'OutputDirectory must be a directory.' }
if ((Test-Path -LiteralPath $output) -and $output -ne $defaultOutput -and
    -not (Test-Path -LiteralPath $marker) -and @(Get-ChildItem -LiteralPath $output -Force).Count -gt 0) {
    throw 'A custom OutputDirectory must be empty or previously generated by build-companion.ps1.'
}
if ((Test-Path -LiteralPath $marker) -and [IO.File]::ReadAllText($marker).Trim() -ne 'DesktopPet.Companion.v1') { throw 'Unrecognized Companion output marker.' }
[void][IO.Directory]::CreateDirectory($output)
[void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($preview))
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition ([IO.File]::ReadAllText((Join-Path $PSScriptRoot 'CharacterBuilder.cs')))

function New-CompanionBase([int]$Index) {
    $left = [int][Math]::Floor($source.Width * $Index / 3.0)
    $right = [int][Math]::Floor($source.Width * ($Index + 1) / 3.0)
    $cell = [CharacterBuilder]::Crop($source, $left, 0, $right - $left, $source.Height)
    $trimmed = $null
    try {
        $cellBounds = [CharacterBuilder]::OpaqueBounds($cell, 25)
        if ($cellBounds.Width -lt 1 -or $cellBounds.Height -lt 1) { throw "Companion source cell $Index has no visible artwork." }
        $trimmed = [CharacterBuilder]::Trim($cell, 25)
        $anchor = 0
        $normalized = [CharacterBuilder]::Normalize($trimmed, 128, 128, 100, 6, [ref]$anchor)
        if ($anchor -ne 122) { $normalized.Dispose(); throw 'Unexpected Companion foot baseline.' }
        return $normalized
    }
    finally { if ($trimmed) { $trimmed.Dispose() }; $cell.Dispose() }
}

function Save-CompanionFrame([string]$Name, $Bitmap) {
    try {
        $destination = Resolve-CompanionPath (Join-Path $output $Name)
        [CharacterBuilder]::Save($Bitmap, $destination)
    }
    finally { $Bitmap.Dispose() }
}

function New-CompanionWalkBase([int]$Row, [int]$Column) {
    $left = [int][Math]::Floor($directional.Width * $Column / 4.0)
    $right = [int][Math]::Floor($directional.Width * ($Column + 1) / 4.0)
    $top = [int][Math]::Floor($directional.Height * $Row / 2.0)
    $bottom = [int][Math]::Floor($directional.Height * ($Row + 1) / 2.0)
    $cell = [CharacterBuilder]::Crop($directional, $left, $top, $right - $left, $bottom - $top)
    $trimmed = $null
    try {
        $bounds = [CharacterBuilder]::OpaqueBounds($cell, 25)
        if ($bounds.Width -lt 1 -or $bounds.Height -lt 1) { throw "Directional source cell $Row/$Column is empty." }
        if ($bounds.Left -eq 0 -or $bounds.Right -ge $cell.Width -or $bounds.Top -eq 0 -or $bounds.Bottom -ge $cell.Height) {
            throw "Directional source cell $Row/$Column touches its border; repair the master rather than clipping it."
        }
        $trimmed = [CharacterBuilder]::Trim($cell, 25)
        $anchor = 0
        return [CharacterBuilder]::Normalize($trimmed, 128, 128, 100, 6, [ref]$anchor)
    }
    finally { if ($trimmed) { $trimmed.Dispose() }; $cell.Dispose() }
}

$source = [CharacterBuilder]::LoadArgb($sourcePath)
$directional = $null
$sidePoses = @(); $turnPoses = @()
$idle = $null; $blink = $null; $sleep = $null
try {
    if ($source.Width -lt 3 -or $source.GetPixel(0, 0).A -ne 0) { throw 'Companion source must be a transparent horizontal three-cell sheet.' }
    $directional = [CharacterBuilder]::LoadArgb($directionalPath)
    if ($directional.Width -lt 4 -or $directional.Height -lt 2 -or $directional.GetPixel(0, 0).A -ne 0) {
        throw 'Companion directional master must be a transparent 2-row, 4-column sheet.'
    }
    for ($i = 0; $i -lt 4; $i++) {
        $sidePoses += New-CompanionWalkBase 0 $i
        $turnPoses += New-CompanionWalkBase 1 $i
    }
    $idle = New-CompanionBase 0
    $blink = New-CompanionBase 1
    $sleep = New-CompanionBase 2
    Save-CompanionFrame 'idle.png' ([CharacterBuilder]::PoseGrounded($idle, 122, 0, 0))
    Save-CompanionFrame 'blink.png' ([CharacterBuilder]::PoseGrounded($blink, 122, 0, 0))
    Save-CompanionFrame 'sit.png' ([CharacterBuilder]::PoseGrounded($idle, 122, 0, 0))
    $rightLook = [CharacterBuilder]::PoseGrounded($turnPoses[0], 122, 0, 0)
    Save-CompanionFrame 'look_right.png' $rightLook
    $leftLook = [CharacterBuilder]::PoseGrounded($turnPoses[0], 122, 0, 0)
    $leftLook.RotateFlip([Drawing.RotateFlipType]::RotateNoneFlipX)
    Save-CompanionFrame 'look_left.png' $leftLook
    Save-CompanionFrame 'drag.png' ([CharacterBuilder]::Pose($idle, 122, 1, 1, -3, 0, 0))
    Save-CompanionFrame 'fall.png' ([CharacterBuilder]::Pose($idle, 122, 1, 1, 4, 0, 0))
    $walkNames = @(); $turnNames = @(); $frontNames = @()
    for ($i = 0; $i -lt 8; $i++) {
        $phase = 2 * [Math]::PI * $i / 8.0
        $name = 'walk_{0}.png' -f ($i + 1)
        $walkNames += $name
        $key = [int][Math]::Floor($i / 2.0)
        # Four actual foot/arm drawings provide the gait; tiny rigid sway adds the in-between sample.
        Save-CompanionFrame $name ([CharacterBuilder]::PoseGrounded($sidePoses[$key], 122, 0.25 * [Math]::Sin($phase), 0))
        $turnName = 'walk_turn_{0}.png' -f ($i + 1)
        $turnNames += $turnName
        Save-CompanionFrame $turnName ([CharacterBuilder]::PoseGrounded($turnPoses[$key], 122, 0.25 * [Math]::Sin($phase), 0))
        $frontName = 'walk_front_{0}.png' -f ($i + 1)
        $frontNames += $frontName
        Save-CompanionFrame $frontName ([CharacterBuilder]::PoseGrounded($idle, 122, 0.65 * [Math]::Sin($phase), 0.15 * [Math]::Sin($phase)))
    }
    $bounds = [CharacterBuilder]::OpaqueBounds($idle, 100)
    # These landmarks were checked against the source: eyes sit halfway down the full
    # outline including the sprout, rather than halfway down the shorter face alone.
    $eyeLeftX = $bounds.Left + $bounds.Width * 0.36
    $eyeRightX = $bounds.Left + $bounds.Width * 0.64
    $eyeY = $bounds.Top + $bounds.Height * 0.50
    for ($i = 0; $i -lt 2; $i++) {
        $frame = [CharacterBuilder]::PoseGrounded($idle, 122, 0, 0)
        [CharacterBuilder]::DrawTearsAt($frame, $eyeLeftX, $eyeY, $eyeRightX, $eyeY, $(if ($i -eq 0) { 0.15 } else { 0.85 }))
        Save-CompanionFrame ('cry_{0}.png' -f ($i + 1)) $frame
        $frame = [CharacterBuilder]::PoseGrounded($idle, 122, $(if ($i -eq 0) { -0.4 } else { 0.4 }), 0)
        [CharacterBuilder]::TintRed($frame, $(if ($i -eq 0) { 0.04 } else { 0.06 }))
        [CharacterBuilder]::DrawAngerMark($frame, 122, 100, $i * 0.3)
        Save-CompanionFrame ('angry_{0}.png' -f ($i + 1)) $frame
        $frame = [CharacterBuilder]::PoseGrounded($sleep, 122, $(if ($i -eq 0) { -0.15 } else { 0.15 }), 0)
        [CharacterBuilder]::DrawSleepMark($frame, 122, 100, $i * 0.4)
        Save-CompanionFrame ('sleep_{0}.png' -f ($i + 1)) $frame
    }
    $manifest = [ordered]@{
        name = 'Companion'; scale = 1.0; frontFacingRest = $true
        frameSizePx = @{ width = 128; height = 128 }
        anchor = @{ x = 64; y = 122 }
        walkSpeedPxPerSec = 54
        frameIntervalMs = 100
        frames = [ordered]@{
            idle = @('idle.png', 'blink.png', 'idle.png', 'blink.png')
            walk = $walkNames; walkTurn = $turnNames; walkFront = $frontNames; sit = @('sit.png')
            lookLeft = @('look_left.png'); lookRight = @('look_right.png')
            drag = @('drag.png'); fall = @('fall.png')
            cry = @('cry_1.png', 'cry_2.png'); angry = @('angry_1.png', 'angry_2.png')
            sleep = @('sleep_1.png', 'sleep_2.png')
        }
        frameDurationsMs = @{ idle = @(4200, 120, 3300, 110) }
        eyePositionsPx = @{ left = @{ x = $eyeLeftX; y = $eyeY }; right = @{ x = $eyeRightX; y = $eyeY } }
    }
    $manifestPath = Resolve-CompanionPath (Join-Path $output 'character.json')
    Set-DesktopPetCharacterBehavior -Definition $manifest -Name 'Companion'
    [IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 8), (New-Object Text.UTF8Encoding $false))
    [IO.File]::WriteAllText($marker, 'DesktopPet.Companion.v1', (New-Object Text.UTF8Encoding $false))

    $samples = @(
        @{ Label = 'Idle'; File = 'idle.png' }, @{ Label = 'Blink / 120 ms'; File = 'blink.png' },
        @{ Label = 'Look left'; File = 'look_left.png' }, @{ Label = 'Look right'; File = 'look_right.png' },
        @{ Label = 'Cry'; File = 'cry_1.png' }, @{ Label = 'Sleep'; File = 'sleep_1.png' }
    )
    foreach ($i in 1..8) { $samples += @{ Label = "Side $i"; File = "walk_$i.png"; Row = 1; Column = $i - 1 } }
    foreach ($i in 1..8) { $samples += @{ Label = "Left $i"; File = "walk_$i.png"; Row = 2; Column = $i - 1; Mirror = $true } }
    foreach ($i in 1..8) { $samples += @{ Label = "Turn $i"; File = "walk_turn_$i.png"; Row = 3; Column = $i - 1 } }
    $sheet = New-Object Drawing.Bitmap (8 * 160),(190 * 4)
    $graphics = [Drawing.Graphics]::FromImage($sheet)
    $font = New-Object Drawing.Font 'Segoe UI',11
    $brush = New-Object Drawing.SolidBrush ([Drawing.Color]::FromArgb(45, 54, 61))
    try {
        $graphics.Clear([Drawing.Color]::FromArgb(240, 244, 247))
        for ($i = 0; $i -lt $samples.Count; $i++) {
            $row = if ($samples[$i].ContainsKey('Row')) { $samples[$i].Row } else { 0 }
            $column = if ($samples[$i].ContainsKey('Column')) { $samples[$i].Column } else { $i }
            $graphics.DrawString($samples[$i].Label, $font, $brush, [single]($column * 160 + 12), [single]($row * 190 + 12))
            $sample = [CharacterBuilder]::LoadArgb((Join-Path $output $samples[$i].File))
            try {
                if ($samples[$i].Mirror) { $sample.RotateFlip([Drawing.RotateFlipType]::RotateNoneFlipX) }
                $graphics.DrawImageUnscaled($sample, ($column * 160 + 16), ($row * 190 + 42))
            } finally { $sample.Dispose() }
        }
        [CharacterBuilder]::Save($sheet, $preview)
    }
    finally { $brush.Dispose(); $font.Dispose(); $graphics.Dispose(); $sheet.Dispose() }
    Write-Output "Companion frames generated: $output"
    Write-Output "Preview: $preview"
}
finally {
    foreach ($pose in $sidePoses + $turnPoses) { $pose.Dispose() }
    if ($directional) { $directional.Dispose() }
    if ($idle) { $idle.Dispose() }; if ($blink) { $blink.Dispose() }; if ($sleep) { $sleep.Dispose() }
    $source.Dispose()
}
